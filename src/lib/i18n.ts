export const dictionaries: Record<Locale, Record<TKey, string>> = { en, ar };

export type Translator = (key: TKey, vars?: Record<string, string | number>) => string;

export function getT(locale: Locale): Translator {
  const dict = dictionaries[locale];
  return (key, vars) => {
    let s: string = dict[key] ?? en[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
    return s;
  };
}

/** Pick a localized string from (en, ar) pairs stored in the DB. */
export function tr(locale: Locale, enText: string, arText?: string | null) {
  return locale === "ar" && arText ? arText : enText;
}

export function intlLocale(locale: Locale) {
  return locale === "ar" ? "ar-EG-u-nu-latn" : "en-GB";
}

export function fmtDate(locale: Locale, date: Date | string) {
  return new Intl.DateTimeFormat(intlLocale(locale), { day: "2-digit", month: "2-digit", year: "numeric" }).format(new Date(date));
}

export function fmtMoney(locale: Locale, cents: number) {
  return new Intl.NumberFormat(locale === "ar" ? "ar-EG-u-nu-latn" : "en-US", {
    style: "currency",
    currency: "EGP",
    minimumFractionDigits: 2,
  }).format(cents / 100);
}

export function fmtNumber(locale: Locale, n: number, digits = 0) {
  return new Intl.NumberFormat(intlLocale(locale), { maximumFractionDigits: digits }).format(n);
}

export function displayName(fullName: string) {
  return fullName.trim().split(/\s+/).slice(0, 2).join(" ");
}

export function initials(fullName: string) {
  return fullName
    .trim()
    .split(/\s+/)
    .slice(0, 2)
    .map((p) => p[0] ?? "")
    .join("")
    .toUpperCase();
}

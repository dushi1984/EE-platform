export type TeacherText = typeof en;
const dict: Record<Locale, TeacherText> = { en, ar };

export function tt(locale: Locale): TeacherText {
  return dict[locale];
}

export function fill(template: string, vars: Record<string, string | number>) {
  return Object.entries(vars).reduce((s, [k, v]) => s.replace(`{${k}}`, String(v)), template);
}

export const TASK_TYPES = ["exercise", "assignment", "essay", "report", "quiz", "worksheet", "lab"] as const;
export const GRADES = ["Grade 10", "Grade 11", "Grade 12"] as const;

export function taskTypeLabel(locale: Locale, type: string) {
  return (dict[locale] as Record<string, string>)[`type_${type}`] ?? type;
}

export function gradeLabel(locale: Locale, grade: string) {
  if (locale !== "ar") return grade;
  if (grade === "Grade 10") return "الصف الأول الثانوي";
  if (grade === "Grade 11") return "الصف الثاني الثانوي";
  if (grade === "Grade 12") return "الصف الثالث الثانوي";
  return grade;
}

export function timeAgo(locale: Locale, date: Date | string) {
  const c = dict[locale];
  const mins = Math.floor((Date.now() - new Date(date).getTime()) / 60000);
  if (mins < 1) return c.justNow;
  if (mins < 60) return fill(c.minAgo, { n: mins });
  const hours = Math.floor(mins / 60);
  if (hours < 24) return fill(c.hoursAgo, { n: hours });
  return fill(c.daysAgo, { n: Math.floor(hours / 24) });
}

export function methodLabel(locale: Locale, method: string) {
  const c = dict[locale];
  if (method === "instapay") return c.instapay;
  if (method === "wallet") return c.wallet;
  if (method === "free") return c.free;
  return c.card;
}
